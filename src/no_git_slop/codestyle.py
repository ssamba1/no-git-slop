"""AI-style habits in code an agent just wrote.

Runs on the added text only (Write content or Edit new_string), so existing code is
never judged. Patterns come from the practitioner tools surveyed for this project
(aislop, slop-scan, windbag, vibecheck, ruff, ESLint) and keep to the low false-positive
subset: each needs a phrase or token humans rarely write by accident.
"""

from __future__ import annotations

import re
from typing import List, Tuple

CODE_EXT = (".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".go", ".rs", ".java", ".kt",
            ".cs", ".rb", ".php", ".swift", ".c", ".cc", ".cpp", ".h", ".hpp", ".sh", ".scala")

# A comment: `#` or `//` at line start or after whitespace (so `http://` is not one), or a block line.
_COMMENT_RE = re.compile(r"(?:^|\s)(?:#|//|/\*+|\*|--)\s?(.*)$")

# Code deleted and replaced by a note: always harmful.
_ELIDED_RE = re.compile(
    r"\.\.\.\s*(?:rest|remaining|existing)\b|\b(?:rest|remainder) of (?:the )?(?:code|file|implementation|function|class)"
    r" (?:remains|stays|is) (?:the same|unchanged|omitted)\b|\b(?:code|implementation|logic) (?:remains|stays) "
    r"(?:the )?(?:same|unchanged)\b|\bexisting code\b.*\bunchanged\b", re.I)
# Comments about the conversation or the edit history rather than the code.
_META_RE = re.compile(
    r"\bas requested\b(?! (?:in|by))|\bper (?:your|the user'?s) request\b|\byou asked\b"
    r"|\bi(?:'ve| have) (?:added|updated|changed|fixed|removed)\b|\bhere'?s the (?:updated|fixed|new)\b"
    r"|\b(?:updated|changed|modified|refactored) to (?:use|return|handle)\b"
    r"|\bnow (?:uses|returns|handles)\b.*\binstead of\b"
    r"|\bgenerated by (?:chatgpt|claude|copilot|an? ai)\b|\bas an ai\b", re.I)
_JS_ESCAPE_RE = re.compile(r"\bas any\b|\bas unknown as\b|@ts-(?:ignore|nocheck)\b|eslint-disable(?!-next-line \S)(?!-line \S)")
_PY_ESCAPE_RE = re.compile(r"#\s*type:\s*ignore(?!\[)|#\s*noqa(?!:)")
_TEST_GAMING_RE = re.compile(
    r"@pytest\.mark\.(?:skip|xfail)\b|\bskipif\(True\b|@unittest\.skip\b|\b(?:it|test|describe)\.(?:skip|only)\("
    r"|^\s*x(?:it|describe)\(|^\s*assert True\b|expect\((true|1)\)\.toBe\(\1\)", re.M)
_PY_DEBUG_RE = re.compile(
    r"^\s*(?:breakpoint\(\)|pdb\.set_trace\(\))|^\s*print\(\s*f?[\"'](?:DEBUG|>>>)|^\s*print\(f[\"'][^\"']*\{\w+=\}", re.M)
_JS_DEBUG_RE = re.compile(r"^\s*debugger;|console\.log\(\s*[\"'](?:DEBUG|>>>)|^\s*dbg!\(", re.M)
_PY_SWALLOW_RE = re.compile(
    r"^\s*except(?:\s+(?:Exception|BaseException))?\s*(?:as \w+)?\s*:\s*(?:\n\s*)?(?:pass|\.\.\.|continue)\s*$", re.M)
_JS_SWALLOW_RE = re.compile(r"\bcatch\s*(?:\([^)]*\))?\s*\{\s*\}")
_EM_DASH = chr(0x2014)


def _comments(text: str) -> List[str]:
    out = []
    for line in text.splitlines():
        m = _COMMENT_RE.search(line)
        if m and m.group(1).strip():
            out.append(m.group(1).strip())
    return out


def code_findings(path: str, text: str) -> Tuple[List[str], List[str]]:
    """(blocking problems, warnings) for code just written to `path`."""
    lower = path.lower()
    if not lower.endswith(CODE_EXT):
        return [], []
    comments = _comments(text)
    is_test = bool(re.search(r"(^|/)(tests?|__tests__|spec)/|(^|/)test_[^/]*$|_test\.\w+$|\.(test|spec)\.\w+$", lower))
    hard, soft = [], []
    elided = next((c for c in comments if _ELIDED_RE.search(c)), None)
    if elided:
        hard.append(f"the comment `{elided[:60]}` stands in for code that was removed. Restore the real code")
    meta = next((c for c in comments if _META_RE.search(c)), None)
    if meta:
        soft.append(f"`{meta[:60]}` talks about the edit or the chat, not the code; say why the code is this way or drop it")
    if (lower.endswith(".py") and _PY_SWALLOW_RE.search(text)) or (not lower.endswith(".py") and _JS_SWALLOW_RE.search(text)):
        soft.append("an exception is caught and silently dropped; handle it, log it with context, or let it raise")
    py = lower.endswith(".py")
    js = lower.endswith((".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx"))
    m = (_PY_ESCAPE_RE if py else _JS_ESCAPE_RE).search(text) if (py or js) else None
    if m:
        soft.append(f"`{m.group(0).strip()}` silences the type checker or linter; fix the cause, or name the rule and say why")
    m = _TEST_GAMING_RE.search(text)
    if m:
        soft.append(f"`{m.group(0).strip()}` skips or fakes a test; fix the code under test instead")
    if not is_test:
        m = (_PY_DEBUG_RE if py else _JS_DEBUG_RE).search(text)
        if m:
            soft.append(f"debug leftover `{m.group(0).strip()[:40]}`; remove it before finishing")
    if any(_EM_DASH in c for c in comments):
        soft.append("a comment uses an em dash; use a period, comma, colon or parentheses")
    return hard, soft
